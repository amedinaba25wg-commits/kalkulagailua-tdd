package com.zubirimanteo.wg32.dvops;

public class Kalkulagailua {
    
    public int batu(int a, int b) {
        return a + b;
    }

    public int kendu(int a, int b) {
        return a - b;
    }

    public int biderkatu(int a, int b) {
        return a * b;
    }
    
    public int zatitu(int a, int b) {
        return a / b;
    }
}